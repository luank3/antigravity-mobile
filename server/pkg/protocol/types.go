package protocol

import (
	"encoding/json"
	"time"
)

// RPCRequest is a JSON-RPC 2.0 request over /agy/rpc/1.0.0.
type RPCRequest struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      any             `json:"id"`
	Method  string          `json:"method"`
	Params  json.RawMessage `json:"params,omitempty"`
}

// RPCError is a JSON-RPC 2.0 error object.
type RPCError struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
	Data    any    `json:"data,omitempty"`
}

// RPCResponse is a JSON-RPC 2.0 response over /agy/rpc/1.0.0.
type RPCResponse struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      any             `json:"id"`
	Result  json.RawMessage `json:"result,omitempty"`
	Error   *RPCError       `json:"error,omitempty"`
}

// EventsSubscribeRequest opens /agy/events/1.0.0 with optional catch-up cursor.
type EventsSubscribeRequest struct {
	SessionIDs []string `json:"sessionIds,omitempty"`
	SinceSeq   uint64   `json:"sinceSeq"`
}

// EventEnvelope wraps ACP updates, permission prompts, and heartbeats with monotonic seq.
type EventEnvelope struct {
	Seq       uint64          `json:"seq"`
	SessionID string          `json:"sessionId,omitempty"`
	Timestamp time.Time       `json:"ts"`
	Kind      string          `json:"kind"` // "session_update" | "permission_request" | "permission_resolved" | "heartbeat" | "replay_complete"
	Payload   json.RawMessage `json:"payload,omitempty"`
}

// BlobUploadHeader initiates a chunked upload on /agy/blob/1.0.0.
type BlobUploadHeader struct {
	SessionID  string `json:"sessionId"`
	Filename   string `json:"filename"`
	MimeType   string `json:"mimeType,omitempty"`
	TotalBytes int64  `json:"totalBytes"`
	SHA256     string `json:"sha256,omitempty"`
}

// BlobUploadResult is returned by agyd after staging an uploaded file under remote /tmp.
type BlobUploadResult struct {
	UploadID   string `json:"uploadId"`
	RemotePath string `json:"remotePath"`
	Filename   string `json:"filename"`
	MimeType   string `json:"mimeType"`
	SizeBytes  int64  `json:"sizeBytes"`
	SHA256     string `json:"sha256"`
	IsImage    bool   `json:"isImage"`
}

// PairRequest is sent by mobile over /agy/pair/1.0.0.
type PairRequest struct {
	Token      string `json:"token"`
	DeviceName string `json:"deviceName"`
	Pin        string `json:"pin,omitempty"`
}

// PairChallenge is returned by agyd with computed SAS for mutual verification.
type PairChallenge struct {
	SessionID  string `json:"sessionId"`
	HostPeerID string `json:"hostPeerId"`
	HostName   string `json:"hostName"`
	SASDigits  string `json:"sasDigits"`
	SASEmojis  string `json:"sasEmojis"`
	Error      string `json:"error,omitempty"`
}

// PairConfirm is sent by mobile after user verifies SAS matches terminal.
type PairConfirm struct {
	SessionID string `json:"sessionId"`
	Accept    bool   `json:"accept"`
}

// PairResult concludes /agy/pair/1.0.0.
type PairResult struct {
	Paired     bool     `json:"paired"`
	HostPeerID string   `json:"hostPeerId,omitempty"`
	HostName   string   `json:"hostName,omitempty"`
	HostOS     string   `json:"hostOs,omitempty"`
	AgyVersion string   `json:"agyVersion,omitempty"`
	RelayAddrs []string `json:"relayAddrs,omitempty"`
	Error      string   `json:"error,omitempty"`
}

// PairInvite describes an active pairing token generated by agyd pair.
type PairInvite struct {
	Token      string   `json:"token"`
	Pin        string   `json:"pin"`
	URI        string   `json:"uri"`
	HostPeerID string   `json:"hostPeerId"`
	HostName   string   `json:"hostName"`
	RelayAddrs []string `json:"relayAddrs"`
	LANAddrs   []string `json:"lanAddrs"`
	ExpiresAt  string   `json:"expiresAt"`
}

// HostInfo is returned by the host/info RPC.
type HostInfo struct {
	HostPeerID     string   `json:"hostPeerId"`
	Hostname       string   `json:"hostname"`
	OS             string   `json:"os"`
	Arch           string   `json:"arch"`
	AgyVersion     string   `json:"agyVersion"`
	WorkspaceRoots []string `json:"workspaceRoots"`
	ListenAddrs    []string `json:"listenAddrs"`
	RelayAddrs     []string `json:"relayAddrs"`
	NATStatus      string   `json:"natStatus"`
	CPUPercent     int      `json:"cpuPercent"`
	RAMPercent     int      `json:"ramPercent"`
	AuthReady      bool     `json:"authReady"`
}

// ConnDiagnostics describes the active libp2p path between mobile and host.
type ConnDiagnostics struct {
	PeerID      string `json:"peerId"`
	Connected   bool   `json:"connected"`
	PathType    string `json:"pathType"` // "lan" | "direct" | "relay" | "disconnected"
	Transport   string `json:"transport"`
	RemoteAddr  string `json:"remoteAddr"`
	RelayPeerID string `json:"relayPeerId,omitempty"`
	RTTMs       int64  `json:"rttMs"`
	IsRelayed   bool   `json:"isRelayed"`
	Error       string `json:"error,omitempty"`
}

// WorkspaceEntry represents a directory entry in workspace/tree.
type WorkspaceEntry struct {
	Name  string `json:"name"`
	Path  string `json:"path"`
	IsDir bool   `json:"isDir"`
	Size  int64  `json:"size"`
}

// GitChange represents a modified file in workspace/git_status.
type GitChange struct {
	Path      string `json:"path"`
	Status    string `json:"status"`
	Additions int    `json:"additions"`
	Deletions int    `json:"deletions"`
}

// ArtifactSummary describes an artifact file under ~/.gemini/antigravity-cli/brain/<session>.
type ArtifactSummary struct {
	Name      string `json:"name"`
	SessionID string `json:"sessionId"`
	Size      int64  `json:"size"`
	UpdatedAt string `json:"updatedAt"`
}

// AuthorizedPeer represents a paired client device in authorized_peers.json.
type AuthorizedPeer struct {
	PeerID     string    `json:"peerId"`
	DeviceName string    `json:"deviceName"`
	PairedAt   time.Time `json:"pairedAt"`
	LastSeenAt time.Time `json:"lastSeenAt"`
}
